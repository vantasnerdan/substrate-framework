"""Global Cartesian Maxwell readouts, not per-cell fields or energy ledgers.

The canonical pair is a=e A_SI/hbar (bohr^-1), Pi=M_a da/dtau
(bohr), tau=t Ry/hbar. There is NO sqrt(N) or N readout multiplier.
For a restricted polarization subspace the Cartesian commutator is i E.T E;
we report its projection without renormalizing it to a fictitious full mode.
"""
import numpy as np

from .joint_ordered_sources import JointProbe
from .physical_field_environment import UniformMaxwellField


OBSERVABLES = ('total-force', 'field-coordinate', 'field-momentum')


def validate_selection(observable, field_axis, q):
    """Reject absent/unsupported fields before allocating a material run."""
    if observable not in OBSERVABLES:
        raise ValueError('unsupported joint observable')
    if observable == 'total-force':
        if field_axis is not None:
            raise ValueError('--field-axis is only valid for a field observable')
        return
    if field_axis not in ('x', 'y', 'z'):
        raise ValueError('field observable requires an explicit Cartesian --field-axis')
    wavevector = np.asarray(q, dtype=float)
    if wavevector.shape != (3,) or not np.isfinite(wavevector).all() or np.any(wavevector != 0):
        raise ValueError('global Maxwell field observable exists only at Gamma q=(0,0,0)')


def global_field_probe(response, field, *, observable, axis):
    """Return a full-PW JointProbe and its physical normalization authority.

    Forward and independently shaped adjoint zero actions are intentional:
    the terminal field observable contains no electronic bilinear. Genuine
    electronic/ionic/field origins are generated by BOTH propagated duals.
    """
    validate_selection(observable, axis, response.q_fractional)
    if observable == 'total-force':
        raise ValueError('global_field_probe requires a field observable')
    if not response.gamma or not response.nfield or not isinstance(field, UniformMaxwellField):
        raise ValueError('actual Gamma response and physical Maxwell field required')
    if (response.nfield != field.size
            or not np.array_equal(response.polarizations, field.polarizations)
            or not np.isclose(response.field_mass, field.mass, rtol=1e-13, atol=0)):
        raise ValueError('response field normalization differs from physical Maxwell authority')
    direction = field.polarizations[:, 'xyz'.index(axis)].copy()
    if not np.any(direction):
        raise ValueError('selected Cartesian field axis is absent from the physical polarization subspace')
    actions = tuple((lambda x, rows=response.sectors[e.target].shape[0]:
                     np.zeros((rows, x.shape[1]), dtype=complex)) for e in response.edges)
    adjoints = tuple((lambda x, rows=response.sectors[e.source].shape[0]:
                      np.zeros((rows, x.shape[1]), dtype=complex)) for e in response.edges)
    coordinate = direction if observable == 'field-coordinate' else np.zeros(field.size)
    momentum = direction if observable == 'field-momentum' else np.zeros(field.size)
    units = 'bohr^-1' if observable == 'field-coordinate' else 'bohr'
    probe = JointProbe(actions, adjoints, np.zeros(response.ndof), np.zeros(response.ndof),
        coordinate, momentum, 'global-'+observable+'-'+axis, units)
    probe.validate(response)
    metadata = dict(observable=observable, field_axis=axis, identity=probe.identity, units=units,
        normalization=field.normalization(), polarization_projection=direction.tolist(),
        global_field=True, readout_multiplier=1, canonical_commutator_axis=float(direction @ direction),
        scope='global Gamma canonical observable; initial-origin connected fluctuations, not energy transfer')
    return probe, metadata
