#!/usr/bin/env python3
"""Cross-check native stdout model identity beyond the full first force audit."""
import ast
import hashlib
import json
import os
from pathlib import Path
import sys
import traceback

HERE=Path(__file__).resolve().parent
AUDIT=HERE.parent
sys.path.insert(0,str(AUDIT))
from run_oracle import context,digest,runtime,save
from native_parse import one,NUMBER


def main():
    report={'status':'running','runtime_start':runtime()}
    try:
        registration=json.loads((HERE/'registration.json').read_text())
        if digest(__file__)!=registration['source_sha256']:
            raise ValueError('Metadata source generation mismatch')
        proof=report['runtime_start']
        if proof['affinity']!=[5] or proof['cgroup_observed']['memory.max']!='2147483648' or any(proof['environment'][k]!='1' for k in ('OMP_NUM_THREADS','OPENBLAS_NUM_THREADS','MKL_NUM_THREADS','NUMEXPR_NUM_THREADS')):
            raise ValueError('Metadata owner resources violated')
        from substrate_framework.verification import CheckLedger
        import sympy as sp
        ledger=CheckLedger('P254-primary-native-metadata')
        c=context();outpath=Path(c['scf']['data']['artifacts']['pw.stdout']['path']);text=outpath.read_text()
        ledger.check('native stdout remains original raw-byte generation',digest(outpath)==c['scf']['data']['artifacts']['pw.stdout']['sha256'])
        settings=c['settings']['scf_settings'];observed={}
        for name,pattern,key in [('ecutwfc_ry',r'kinetic-energy cutoff\s*=\s*('+NUMBER+r')','ecutwfc_ry'),
                                ('ecutrho_ry',r'charge density cutoff\s*=\s*('+NUMBER+r')','ecutrho_ry'),
                                ('conv_thr_ry',r'scf convergence threshold\s*=\s*('+NUMBER+r')','conv_thr_ry'),
                                ('degauss_ry',r'Marzari-Vanderbilt smearing, width \(Ry\)=\s*('+NUMBER+r')','degauss_ry')]:
            value=sp.Rational(one(pattern,text));expected=sp.Rational(str(settings[key]));observed[name]=str(value)
            ledger.mutation_sensitive('native stdout '+name,lambda x:x==expected,value,[value*2])
        ledger.check('native stdout exchange-correlation is PBE',one(r'Exchange-correlation=\s*(\w+)',text.split('bravais-lattice index')[0])=='PBE')
        ledger.check('native stdout atom and type counts',int(one(r'number of atoms/cell\s*=\s*(\d+)',text))==37 and int(one(r'number of atomic types\s*=\s*(\d+)',text))==2)
        charges=[];pseudo_records=[]
        for symbol,count in [('Ni',31),('H',6)]:
            execution=c['spec']['execution'];path=Path(execution['pseudo_dir'])/execution['pseudopotentials'][symbol]
            content=path.read_bytes();charge=sp.Rational(one(r'^\s*('+NUMBER+r')\s+Z valence',content.decode()))
            charges.append(count*charge)
            native_section=text.split('for '+symbol)[1].split('Generated by')[0]
            native_charge=sp.Rational(one(r'Zval =\s*('+NUMBER+r')',native_section))
            native_md5=one(r'MD5 check sum:\s*([0-9a-f]+)',native_section)
            ledger.mutation_sensitive(symbol+' native pseudovalence identity',lambda x:x==charge,native_charge,[native_charge+1])
            ledger.mutation_sensitive(symbol+' native pseudo MD5 raw-byte binding',lambda x:x==hashlib.md5(content).hexdigest(),native_md5,['0'*32])
            pseudo_records.append({'species':symbol,'count':count,'path':str(path),'valence':str(charge),'native_md5':native_md5,'raw_sha256':hashlib.sha256(content).hexdigest()})
        electrons=sp.Rational(one(r'number of electrons\s*=\s*('+NUMBER+r')',text))
        ledger.mutation_sensitive('native electron count equals independent exact composition dot pseudovalence',lambda x:x==sum(charges),electrons,[electrons+1])
        # This is parser publication precision, not the geometry's physical uncertainty.
        source=next(p for p in c['plan']['input_sources_sha256'] if p.endswith('/qe_io.py'))
        tree=ast.parse(Path(source).read_text())
        tolerance=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='GEOMETRY_ATOL_ANGSTROM' for t in n.targets))
        ledger.mutation_sensitive('SCF published geometry tolerance matches bound source',lambda x:x==tolerance,c['scf']['data']['geometry_tolerance_angstrom'],[tolerance*10])
        ledger.check('published optimizer gate equals frozen relaxation gate',c['relax']['optimizer']==c['settings']['optimizer'] and c['settings']['optimizer']['fmax_ev_per_angstrom']==0.005)
        ledger.check('durable optimizer pending geometry equals published final',c['optimizer']['state']['pending_positions_angstrom']==c['published']['data']['geometry']['positions_angstrom'])
        ledger.finish()
        report.update(status='complete',observed_stdout_settings=observed,pseudos=pseudo_records,electron_count=str(electrons),geometry_publication_tolerance_angstrom=tolerance,checks=ledger.passed,check_count=len(ledger.passed),runtime_end=runtime(),registration_sha256=digest(HERE/'registration.json'))
        save(HERE/'receipt.json',report)
        print('PRIMARY_METADATA_COMPLETE',digest(HERE/'receipt.json'),flush=True)
        return 0
    except BaseException:
        report.update(status='failed',traceback=traceback.format_exc(),runtime_end=runtime())
        save(HERE/'failure.json',report);traceback.print_exc();print('PRIMARY_METADATA_TERMINAL_FAILURE',flush=True)
        return 2


if __name__=='__main__':
    raise SystemExit(main())
